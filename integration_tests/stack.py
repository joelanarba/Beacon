ROOT = Path(__file__).resolve().parents[1]
COMPOSE = ROOT / "docker-compose.integration.yml"
PASSWORD = "integration-only"
DATABASE = "beacon_test_e2e"
RUN_LABEL = "com.beacon.integration.run"
SERVICES = {"postgres", "redis", "rabbitmq", "app"}


def redact(value: str) -> str:
    value = re.sub(r"\beyJ[\w-]+\.[\w-]+\.[\w-]+", "[redacted-jwt]", value)
    return re.sub(r"(\w+(?:\+\w+)?://[^\s:/]+:)[^\s@]+@", r"\1[redacted]@", value)


def isolated_env(project: str, image: str) -> dict[str, str]:
    env = {
        k: v
        for k, v in os.environ.items()
        if not k.startswith(("COMPOSE_", "BEACON_IT_", "BEACON_TEST_"))
    }
    env.update(BEACON_IT_PROJECT=project, BEACON_IT_IMAGE=image)
    return env


def check_project(project: str) -> None:
    if not re.fullmatch(r"beacon-it-[a-f0-9]{32}", project):
        raise ValueError(
            "Refusing an integration project name not generated by the runner"
        )


def loopback_port(output: str) -> int:
    match = re.fullmatch(r"127\.0\.0\.1:([0-9]+)", output.strip())
    if not match or not 0 < int(match[1]) < 65536:
        raise ValueError("Refusing a non-loopback or invalid Compose port binding")
    return int(match[1])


class DockerRun:
    def __init__(self, artifacts: Path):
        self.artifacts = artifacts
        artifacts.mkdir(parents=True, exist_ok=True)
        self.empty_env = artifacts / "empty.env"
        with self.empty_env.open("x", encoding="utf-8"):
            pass
        self.image = "beacon-integration:" + uuid.uuid4().hex

    def run(self, args, *, env=None, check=True, timeout=180):
        started = datetime.now(UTC).isoformat()
        try:
            result = subprocess.run(
                args,
                cwd=ROOT,
                env=env,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                timeout=timeout,
                encoding="utf-8",
                errors="replace",
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            self.record({"started": started, "argv": args, "error": str(exc)})
            raise
        self.record(
            {
                "started": started,
                "finished": datetime.now(UTC).isoformat(),
                "argv": args,
                "exit_code": result.returncode,
                "output": result.stdout,
            }
        )
        if check and result.returncode:
            raise RuntimeError(
                f"Command failed ({result.returncode}): "
                f"{redact(' '.join(args))}\n{redact(result.stdout[-6000:])}"
            )
        return result

    def record(self, data):
        with (self.artifacts / "commands.jsonl").open("a", encoding="utf-8") as stream:
            stream.write(redact(json.dumps(data, default=str)) + "\n")

    def preflight(self):
        self.run(["docker", "version"])
        self.run(["docker", "compose", "version"])
        endpoint = (
            os.getenv("DOCKER_HOST")
            or self.run(
                [
                    "docker",
                    "context",
                    "inspect",
                    "--format",
                    '{{(index .Endpoints "docker").Host}}',
                ]
            ).stdout.strip()
        )
        if not endpoint.startswith(("unix://", "npipe://")):
            raise RuntimeError("Use a local Docker socket, not a remote Docker context")
        self.run(["git", "rev-parse", "HEAD"])
        self.run(["git", "status", "--short"])

    def build(self):
        build = Stack(self, seed=False)
        try:
            build.compose("config", "--quiet")
            build.compose("build", "app", timeout=900)
            self.run(
                [
                    "docker",
                    "image",
                    "inspect",
                    self.image,
                    "--format",
                    "{{json .Id}} {{json .RepoDigests}}",
                ]
            )
            build.compose(
                "run", "--rm", "--no-deps", "migrate", "python", "-m", "pip", "freeze"
            )
        finally:
            # Even a failed one-shot container can leave a project network.
            build.cleanup()


class Stack:
    def __init__(self, run: DockerRun, *, seed=True, broker=True):
        self.run = run
        self.project = "beacon-it-" + uuid.uuid4().hex
        check_project(self.project)
        self.env = isolated_env(self.project, run.image)
        self.artifacts = run.artifacts / self.project
        self.artifacts.mkdir()
        self.seed_requested, self.broker_requested = seed, broker
        self.ports: dict[str, int] = {}
        self.responders: list[str] = []
        self.hospital: str | None = None

    def compose(self, *args, check=True, timeout=180):
        check_project(self.project)
        return self.run.run(
            [
                "docker",
                "compose",
                "--ansi",
                "never",
                "--env-file",
                str(self.run.empty_env),
                "-f",
                str(COMPOSE),
                "-p",
                self.project,
                *args,
            ],
            env=self.env,
            check=check,
            timeout=timeout,
        )

    def verify_ownership(self):
        check_project(self.project)
        for kind, listing in (
            ("container", ["ps", "-aq"]),
            ("volume", ["volume", "ls", "-q"]),
            ("network", ["network", "ls", "-q"]),
        ):
            ids = self.run.run(
                [
                    "docker",
                    *listing,
                    "--filter",
                    f"label=com.docker.compose.project={self.project}",
                ]
            ).stdout.split()
            for resource in ids:
                data = json.loads(
                    self.run.run(["docker", kind, "inspect", resource]).stdout
                )[0]
                labels = (
                    data.get("Config", {}).get("Labels", {})
                    if kind == "container"
                    else data.get("Labels", {})
                ) or {}
                if labels.get(RUN_LABEL) != self.project:
                    raise RuntimeError(f"Refusing to mutate unowned {kind}: {resource}")

    def port(self, service: str, internal: int) -> int:
        return loopback_port(self.compose("port", service, str(internal)).stdout)

    async def prepare(self):
        services = ["postgres", "redis"] + (
            ["rabbitmq"] if self.broker_requested else []
        )
        self.compose(
            "up", "-d", "--wait", "--wait-timeout", "180", *services, timeout=240
        )
        self.ports.update(
            pg=self.port("postgres", 5432), redis=self.port("redis", 6379)
        )
        assert not await self.sql(
            "SELECT tablename FROM pg_tables WHERE schemaname='public'"
        )
        self.compose("run", "--rm", "--no-deps", "migrate")
        self.compose(
            "run", "--rm", "--no-deps", "migrate", "alembic", "upgrade", "head"
        )
        self.compose("run", "--rm", "--no-deps", "migrate", "alembic", "current")
        assert (
            await self.scalar("SELECT version_num FROM alembic_version")
            == "20261019_0002"
        )
        if self.broker_requested:
            self.broker_ports()
        if self.seed_requested:
            await self.seed()
        images = ["postgres:16-alpine", "redis:7.2-alpine"]
        if self.broker_requested:
            images.append("rabbitmq:3.13-management-alpine")
        for image in images:
            self.run.run(
                [
                    "docker",
                    "image",
                    "inspect",
                    image,
                    "--format",
                    "{{json .Id}} {{json .RepoDigests}}",
                ]
            )
        self.run.record({"project": self.project, "event": "prepared"})

    def broker_ports(self):
        self.ports.update(
            amqp=self.port("rabbitmq", 5672), management=self.port("rabbitmq", 15672)
        )

    async def sql(self, query, *args, database=DATABASE):
        if database not in {DATABASE, "beacon_test_regression"}:
            raise ValueError("Refusing an unexpected database")
        conn = await asyncpg.connect(
            host="127.0.0.1",
            port=self.ports["pg"],
            user="beacon_test",
            password=PASSWORD,
            database=database,
            timeout=5,
            command_timeout=10,
        )
        try:
            assert await conn.fetchval("SELECT current_database()") == database
            return [dict(row) for row in await conn.fetch(query, *args)]
        finally:
            await conn.close(timeout=5)

    async def scalar(self, query, *args):
        rows = await self.sql(query, *args)
        return next(iter(rows[0].values())) if rows else None

    @asynccontextmanager
    async def redis(self):
        client = redis.Redis(
            host="127.0.0.1",
            port=self.ports["redis"],
            db=15,
            decode_responses=True,
            socket_timeout=3,
            socket_connect_timeout=3,
        )
        try:
            yield client
        finally:
            await client.aclose()

    async def seed(self):
        for kind in ("AMBULANCE", "FIRE", "POLICE"):
            for index in range(4):
                rid = uuid.uuid4()
                await self.sql(
                    """INSERT INTO responders
                    (id,name,type,status,contact,reachable_channel)
                    VALUES ($1,$2,$3,'AVAILABLE',$4,'SMS')""",
                    rid,
                    f"Synthetic {kind} {index}",
                    kind,
                    f"synthetic-{rid}",
                )
                async with self.redis() as rc:
                    await rc.geoadd("responders:live", [-0.1969, 5.555, str(rid)])
                self.responders.append(str(rid))
        hid = uuid.uuid4()
        await self.sql(
            """INSERT INTO hospitals
            (id,name,latitude,longitude,total_capacity,available_capacity,specialties)
            VALUES ($1,'Synthetic TRAUMA hospital',5.555,-0.1969,
                    4,4,ARRAY['TRAUMA'])""",
            hid,
        )
        self.hospital = str(hid)
        await self.sql(
            """INSERT INTO users
            (id,email,full_name,hashed_password,role,is_active)
            VALUES ($1,'integration@example.com','Synthetic dispatcher',
                    $2,'DISPATCHER',true)""",
            uuid.uuid4(),
            bcrypt.hash("integration-password"),
        )

    async def start_app(self, *, ready=True):
        self.compose("up", "-d", "--no-deps", "app")
        self.ports.update(http=self.port("app", 8000), control=self.port("app", 9010))
        await self.wait_http("/health", 200)
        if ready:
            await self.wait_http("/ready", 200, timeout=90)

    @property
    def url(self):
        return f"http://127.0.0.1:{self.ports['http']}"

    async def http(self, method, path, **kwargs):
        async with httpx.AsyncClient(
            base_url=self.url, trust_env=False, timeout=10
        ) as client:
            return await client.request(method, path, **kwargs)

    async def wait(self, predicate, *, timeout=90, description="condition"):
        deadline = time.monotonic() + timeout
        last_error = None
        while time.monotonic() < deadline:
            try:
                result = await predicate()
                if result:
                    return result
            except (
                OSError,
                TimeoutError,
                httpx.HTTPError,
                asyncpg.PostgresError,
                redis.RedisError,
            ) as exc:
                last_error = type(exc).__name__
            await asyncio.sleep(0.1)
        raise AssertionError(
            f"Timed out waiting for {description}; last error={last_error}"
        )

    async def wait_http(self, path, status, *, timeout=90):
        async def check():
            return (await self.http("GET", path)).status_code == status

        await self.wait(check, timeout=timeout, description=f"{path} HTTP {status}")

    async def control(self, path, body=None):
        async with httpx.AsyncClient(trust_env=False, timeout=5) as client:
            url = f"http://127.0.0.1:{self.ports['control']}{path}"
            response = (
                await client.get(url)
                if body is None
                else await client.post(url, json=body)
            )
            response.raise_for_status()
            return response.json()

    async def arm(self, stage, routing_key="incident.reported"):
        await self.control("/arm", {"stage": stage, "routing_key": routing_key})

    async def barrier(self):
        async def reached():
            state = await self.control("/state")
            return state if state["reached"] else None

        return await self.wait(reached, description="worker fault barrier")

    async def login(self):
        response = await self.http(
            "POST",
            "/auth/login",
            json={
                "email": "integration@example.com",
                "password": "integration-password",
            },
        )
        assert response.status_code == 200
        return response.json()["access_token"]

    async def ingest(self, key=None, **overrides):
        body = {
            "emergency_type": "MEDICAL",
            "latitude": 5.555,
            "longitude": -0.1969,
            "description": "Synthetic integration incident",
        }
        body.update(overrides)
        headers = {"Idempotency-Key": key} if key else {}
        response = await self.http("POST", "/ingest/app", json=body, headers=headers)
        assert response.status_code == 201
        return response.json()["incident_id"]

    async def assigned(self, incident_id):
        async def check():
            return await self.scalar(
                "SELECT status='ASSIGNED' FROM incidents WHERE id=$1::text::uuid",
                incident_id,
            )

        await self.wait(check, description=f"assignment of {incident_id}")

    async def status(self, incident_id, status, token):
        response = await self.http(
            "POST",
            f"/incidents/{incident_id}/status",
            json={"status": status},
            headers={"Authorization": f"Bearer {token}"},
        )
        assert response.status_code == 200
        return response.json()

    async def sms(self):
        async with self.redis() as rc:
            return [json.loads(row) for row in await rc.lrange("sim:sms:outbox", 0, -1)]

    async def notified(self, incident_id):
        async def check():
            return [
                m
                for m in await self.sms()
                if incident_id.split("-")[0].upper() in m["message"]
            ]

        return await self.wait(check, description="simulated SMS delivery")

    @asynccontextmanager
    async def amqp(self):
        conn = await aio_pika.connect(
            host="127.0.0.1",
            port=self.ports["amqp"],
            login="beacon_test",
            password=PASSWORD,
            timeout=5,
        )
        try:
            channel = await conn.channel(publisher_confirms=True, on_return_raises=True)
            exchange = await channel.get_exchange("beacon.events")
            yield channel, exchange
        finally:
            await conn.close()

    async def publish(self, routing_key, payload, event_id, attempt=0):
        body = payload if isinstance(payload, bytes) else json.dumps(payload).encode()
        async with self.amqp() as (_, exchange):
            await exchange.publish(
                aio_pika.Message(
                    body=body,
                    message_id=event_id,
                    priority=10,
                    headers={"x-beacon-attempt": attempt},
                    delivery_mode=aio_pika.DeliveryMode.PERSISTENT,
                ),
                routing_key=routing_key,
                mandatory=True,
                timeout=5,
            )

    async def event(self, incident_id, routing_key="incident.reported"):
        row = (
            await self.sql(
                """SELECT event_id,payload FROM event_outbox
            WHERE event_id=$1 AND delivery_attempt=0""",
                f"{routing_key}:{incident_id}",
            )
        )[0]
        return row["event_id"], json.loads(row["payload"])

    async def queues(self):
        # Query live queue processes, rather than cached management API metrics.
        output = self.compose(
            "exec",
            "-T",
            "rabbitmq",
            "rabbitmqctl",
            "list_queues",
            "--quiet",
            "--formatter=json",
            "name",
            "messages_ready",
            "messages_unacknowledged",
            "consumers",
        ).stdout
        rows = json.loads(output)
        for row in rows:
            row["messages"] = row["messages_ready"] + row["messages_unacknowledged"]
        return rows

    async def idle(self):
        async def check():
            if await self.scalar(
                "SELECT count(*) FROM event_outbox WHERE published_at IS NULL"
            ):
                return False
            queues = await self.queues()
            workers = [
                q
                for q in queues
                if q["name"] in {"dispatch.incoming", "notify.outgoing"}
            ]
            return len(workers) == 2 and all(
                q["messages"] == 0 and q["consumers"] >= 1 for q in workers
            )

        await self.wait(check, description="published outbox and drained worker queues")

    def fault(self, action, service):
        if service not in SERVICES or action not in {"stop", "start", "kill"}:
            raise ValueError("Unsupported scoped fault")
        self.verify_ownership()
        args = (
            ("kill", "-s", "SIGKILL", service)
            if action == "kill"
            else (action, service)
        )
        self.compose(*args)
        self.run.record(
            {
                "project": self.project,
                "fault": action,
                "service": service,
                "at": datetime.now(UTC).isoformat(),
            }
        )

    async def recover(self, service, *, ready=True):
        self.verify_ownership()
        self.compose(
            "up",
            "-d",
            "--no-deps",
            "--wait",
            "--wait-timeout",
            "180",
            service,
            timeout=240,
        )
        # Docker may allocate new ephemeral host ports when a container starts
        # again. Application peers use service DNS; controller probes use these.
        if service == "postgres":
            self.ports["pg"] = self.port("postgres", 5432)
        if service == "redis":
            self.ports["redis"] = self.port("redis", 6379)
        if service == "rabbitmq":
            self.broker_ports()
        if service == "app":
            self.ports.update(
                http=self.port("app", 8000), control=self.port("app", 9010)
            )
        if ready:
            await self.wait_http("/ready", 200)

    async def invariants(self):
        assert (
            await self.scalar(
                """SELECT count(*) FROM hospitals
            WHERE available_capacity < 0 OR available_capacity > total_capacity"""
            )
            == 0
        )
        assert not await self.sql(
            """SELECT incident_id FROM assignments
            GROUP BY incident_id HAVING count(*) > 1"""
        )
        assert not await self.sql(
            """SELECT responder_id FROM assignments WHERE released_at IS NULL
            GROUP BY responder_id HAVING count(*) > 1"""
        )

    async def capture(self):
        queries = {
            "incidents": "SELECT id,status,source_channel FROM incidents",
            "assignments": "SELECT * FROM assignments",
            "hospitals": "SELECT id,total_capacity,available_capacity FROM hospitals",
            "outbox": (
                "SELECT event_id,delivery_attempt,publish_attempts,"
                "available_at,created_at,published_at,last_error "
                "FROM event_outbox ORDER BY created_at"
            ),
            "dead_letters": (
                "SELECT consumer,event_id,delivery_attempt,error_type "
                "FROM dead_letters"
            ),
        }
        for name, query in queries.items():
            try:
                data = await self.sql(query)
            except Exception as exc:
                data = {"capture_error": type(exc).__name__}
            (self.artifacts / f"{name}.json").write_text(
                json.dumps(data, default=str, indent=2), encoding="utf-8"
            )
        for name, getter in (("queues", self.queues), ("sms", self.sms)):
            try:
                data = await getter()
            except Exception as exc:
                data = {"capture_error": type(exc).__name__}
            (self.artifacts / f"{name}.json").write_text(
                json.dumps(data, default=str, indent=2), encoding="utf-8"
            )

    def cleanup(self):
        self.verify_ownership()
        for name, args in (
            ("containers", ("ps", "--all")),
            ("images", ("images",)),
            ("services", ("logs", "--no-color", "--timestamps")),
        ):
            output = self.compose(*args, check=False).stdout
            (self.artifacts / f"{name}.log").write_text(
                redact(output), encoding="utf-8"
            )
        self.compose("down", "--volumes", "--remove-orphans", timeout=180)
        # Fail cleanup rather than silently leaving any project resources behind.
        for listing in (["ps", "-aq"], ["volume", "ls", "-q"], ["network", "ls", "-q"]):
            assert not self.run.run(
                [
                    "docker",
                    *listing,
                    "--filter",
                    f"label=com.docker.compose.project={self.project}",
                ]
            ).stdout.strip()
